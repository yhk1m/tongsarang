def is_moc(category):
    """모평·수능인가 (= 학년도 표기가 확실한 구간)"""
    return category in ('수능', '6모', '9모', '6월', '9월', '11월')


def to_ebsi(subject, school_year, category):
    """(학년도, 분류) → (EBSi 시행연도, 월 후보 목록). 알 수 없으면 (None, None)."""
    month = CATEGORY_TO_MONTH.get(category)
    if not month:
        return None, None
    year = int(school_year)
    if is_moc(category):
        exam_year = year - 1            # 모평·수능은 전 과목 학년도 표기
    elif subject in HAKPYEONG_BY_EXAM_YEAR:
        exam_year = year                # 학평을 시행연도로 적는 과목
    else:
        exam_year = year - 1            # 학평도 학년도로 적는 과목
    return exam_year, MONTH_CANDIDATES.get(month, [month])


