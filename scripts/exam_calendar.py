def megastudy_seq(subject, school_year, category):
    """(학년도, 분류) → 메가스터디 examSeq. 표에 없으면 None."""
    exam_year, _months = to_ebsi(subject, school_year, category)
    month = CATEGORY_TO_MONTH.get(category)
    if exam_year is None or month is None:
        return None
    return MEGASTUDY_SEQ.get((exam_year, month))


def image_code(subject, grade=''):
    if subject == '통합사회' and grade == '고2':
        return 'iss2'
    return SUBJECT_EBSI[subject][0]


def image_name(subject, school_year, category, number, grade=''):
    month = CATEGORY_TO_MONTH.get(category, '00')
    return f'{school_year}_{month}_{image_code(subject, grade)}_{int(number):02d}'
